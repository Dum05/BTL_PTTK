CREATE TABLE IF NOT EXISTS account (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL CHECK (role IN ('CUSTOMER','WAREHOUSE','MANAGER','CASHIER'))
);
CREATE TABLE IF NOT EXISTS member_profile (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL UNIQUE REFERENCES account(id),
    full_name VARCHAR(120) NOT NULL,
    birth_date DATE NOT NULL,
    phone VARCHAR(10) NOT NULL UNIQUE,
    email VARCHAR(150) NOT NULL UNIQUE,
    address VARCHAR(250) NOT NULL,
    registered_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS supplier (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(140) NOT NULL,
    name_key VARCHAR(140) NOT NULL UNIQUE,
    phone VARCHAR(10) NOT NULL,
    address VARCHAR(250) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS product (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku VARCHAR(30) NOT NULL UNIQUE,
    name VARCHAR(140) NOT NULL,
    stock BIGINT NOT NULL DEFAULT 0 CHECK (stock >= 0),
    active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS goods_receipt (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_id BIGINT NOT NULL REFERENCES supplier(id),
    employee_id BIGINT NOT NULL REFERENCES account(id),
    request_key UUID NOT NULL,
    received_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (employee_id, request_key)
);
CREATE TABLE IF NOT EXISTS goods_receipt_line (
    receipt_id BIGINT NOT NULL REFERENCES goods_receipt(id),
    product_id BIGINT NOT NULL REFERENCES product(id),
    quantity INTEGER NOT NULL CHECK (quantity BETWEEN 1 AND 1000000),
    unit_price DECIMAL(15,0) NOT NULL CHECK (unit_price > 0),
    PRIMARY KEY (receipt_id, product_id)
);

-- Các bảng dự trù cho nghiệp vụ bán hàng ngoài hai module được triển khai.
CREATE TABLE IF NOT EXISTS sales_order (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT REFERENCES account(id),
    employee_id BIGINT REFERENCES account(id),
    channel VARCHAR(12) NOT NULL CHECK (channel IN ('ONLINE','COUNTER')),
    status VARCHAR(20) NOT NULL,
    ordered_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK ((channel = 'ONLINE' AND customer_id IS NOT NULL)
        OR (channel = 'COUNTER' AND employee_id IS NOT NULL))
);
CREATE TABLE IF NOT EXISTS sales_line (
    order_id BIGINT NOT NULL REFERENCES sales_order(id),
    product_id BIGINT NOT NULL REFERENCES product(id),
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    unit_price DECIMAL(15,0) NOT NULL CHECK (unit_price >= 0),
    PRIMARY KEY (order_id, product_id)
);
