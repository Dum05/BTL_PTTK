-- Nâng cấp CSDL v1/v2: H2 đổi tên tại chỗ và giữ dữ liệu, khóa, IDENTITY.
-- Khi bảng cũ không tồn tại, lệnh không thay đổi gì. Không xóa dữ liệu.
ALTER TABLE IF EXISTS account RENAME TO tblAccount4;
ALTER TABLE IF EXISTS member_profile RENAME TO tblMemberProfile4;
ALTER TABLE IF EXISTS supplier RENAME TO tblSupplier4;
ALTER TABLE IF EXISTS product RENAME TO tblProduct4;
ALTER TABLE IF EXISTS goods_receipt RENAME TO tblGoodsReceipt4;
ALTER TABLE IF EXISTS goods_receipt_line RENAME TO tblReceiptLine4;
ALTER TABLE IF EXISTS sales_order RENAME TO tblSalesOrder4;
ALTER TABLE IF EXISTS sales_line RENAME TO tblSalesLine4;

CREATE TABLE IF NOT EXISTS tblAccount4 (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL CHECK (role IN ('CUSTOMER','WAREHOUSE','MANAGER','CASHIER'))
);
CREATE TABLE IF NOT EXISTS tblMemberProfile4 (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL UNIQUE REFERENCES tblAccount4(id),
    full_name VARCHAR(120) NOT NULL,
    birth_date DATE NOT NULL,
    phone VARCHAR(10) NOT NULL UNIQUE,
    email VARCHAR(150) NOT NULL UNIQUE,
    address VARCHAR(250) NOT NULL,
    registered_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS tblSupplier4 (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(140) NOT NULL,
    name_key VARCHAR(140) NOT NULL UNIQUE,
    phone VARCHAR(10) NOT NULL,
    address VARCHAR(250) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS tblProduct4 (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku VARCHAR(30) NOT NULL UNIQUE,
    name VARCHAR(140) NOT NULL,
    stock BIGINT NOT NULL DEFAULT 0 CHECK (stock >= 0),
    active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS tblGoodsReceipt4 (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_id BIGINT NOT NULL REFERENCES tblSupplier4(id),
    employee_id BIGINT NOT NULL REFERENCES tblAccount4(id),
    request_key UUID NOT NULL,
    received_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (employee_id, request_key)
);
CREATE TABLE IF NOT EXISTS tblReceiptLine4 (
    receipt_id BIGINT NOT NULL REFERENCES tblGoodsReceipt4(id),
    product_id BIGINT NOT NULL REFERENCES tblProduct4(id),
    quantity INTEGER NOT NULL CHECK (quantity BETWEEN 1 AND 1000000),
    unit_price DECIMAL(15,0) NOT NULL CHECK (unit_price > 0),
    PRIMARY KEY (receipt_id, product_id)
);

-- Các bảng dự trù cho nghiệp vụ bán hàng ngoài hai module được triển khai.
CREATE TABLE IF NOT EXISTS tblSalesOrder4 (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT REFERENCES tblAccount4(id),
    employee_id BIGINT REFERENCES tblAccount4(id),
    channel VARCHAR(12) NOT NULL CHECK (channel IN ('ONLINE','COUNTER')),
    status VARCHAR(20) NOT NULL,
    ordered_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK ((channel = 'ONLINE' AND customer_id IS NOT NULL)
        OR (channel = 'COUNTER' AND employee_id IS NOT NULL))
);
CREATE TABLE IF NOT EXISTS tblSalesLine4 (
    order_id BIGINT NOT NULL REFERENCES tblSalesOrder4(id),
    product_id BIGINT NOT NULL REFERENCES tblProduct4(id),
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    unit_price DECIMAL(15,0) NOT NULL CHECK (unit_price >= 0),
    PRIMARY KEY (order_id, product_id)
);
